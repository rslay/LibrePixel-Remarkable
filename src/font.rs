pub fn glyph(ch: char) -> &'static [u8; 7] {
    let ch = ch.to_ascii_uppercase();
    let idx = match ch {
        'A'..='Z' => ch as usize - 'A' as usize,
        '0'..='9' => 26 + (ch as usize - '0' as usize),
        '!' => 37, '.' => 38, ':' => 39, '-' => 40, ',' => 41,
        '?' => 42, '(' => 43, ')' => 44, '/' => 45,
        _ => 36, // space for anything unknown
    };
    &GLYPHS[idx]
}
